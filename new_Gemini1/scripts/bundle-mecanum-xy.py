"""Bundle the supplied XY controller, preserving its PID, filters and fail-safes.
Run after deliberately updating the reference firmware. No network required.
"""
from pathlib import Path
import json,re
root=Path(__file__).resolve().parents[1]
source=root/'codebackupmicronw/mechanum-withencodrxy'
seen=set()
def expand(path):
    if path.name in seen: return ''
    seen.add(path.name)
    text=path.read_text().replace('#pragma once','')
    return re.sub(r'#include "([^"]+)"',lambda m:expand(source/'include'/m[1]),text)
text=expand(source/'src/main.cpp')
text=text.replace('OmniTwist','MecanumTwist').replace('omniTwistToRpm','mecanumTwistToRpm').replace('OMNI_HALF','MECANUM_HALF').replace('Four-wheel omni X-drive geometry.','Four-wheel mecanum X roller geometry; parallel wheel axles.').replace('45-degree omni wheels in an X pattern:','45-degree mecanum rollers in an X pattern:').replace('X-drive omni motion','mecanum motion')
(root/'public/mecanum-xy-source.js').write_text('// Generated by scripts/bundle-mecanum-xy.py from the supplied reference.\nconst MECANUM_XY_SOURCE = '+json.dumps(text,ensure_ascii=False)+';\n')

# The reference depends on local BNO08x startup fixes, not the registry version.
lib=source/'lib/Adafruit BNO08x'
files={}
for entry in sorted(lib.rglob('*')):
    if entry.is_file() and (entry.relative_to(lib).parts[0]=='src' or entry.name in ['library.properties','license.txt','LOCAL_CHANGES.md']):
        files['lib/Adafruit BNO08x/'+entry.relative_to(lib).as_posix()]=entry.read_text()
with (root/'public/mecanum-xy-source.js').open('a') as output:
    output.write('const MECANUM_XY_LIBRARIES = '+json.dumps(files,ensure_ascii=False)+';\n')
