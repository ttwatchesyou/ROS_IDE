function parseProjectScanOutput(stdout) {
  const marker = 'ROSIDE_PROJECT_SUMMARY=';
  const line = String(stdout || '').split(/\r?\n/).reverse().find(value => value.startsWith(marker));
  if (!line) throw new Error('Project scan returned no result');
  return JSON.parse(line.slice(marker.length));
}

function scanLocalProject(workspace) {
  const root=path.resolve(String(workspace||'')),sourceRoot=path.join(root,'src');
  const hits=Object.fromEntries(Object.keys(CAPABILITY_PATTERNS).map(key=>[key,new Set()]));
  const packages=[],languages=new Set(),skipDirs=new Set(['build','install','log','node_modules','__pycache__','.git','.idea','.vscode']);
  const allowedExt=new Set(['.py','.cpp','.cc','.cxx','.c','.h','.hh','.hpp','.xml','.urdf','.xacro','.yaml','.yml','.launch','.cmake','.txt','.json']);
  let fileCount=0,totalBytes=0,truncated=false;
  const walk=directory=>{
    if(truncated)return;
    let entries=[];try{entries=fs.readdirSync(directory,{withFileTypes:true});}catch{return;}
    for(const entry of entries){
      if(entry.isDirectory()){
        if(!skipDirs.has(entry.name)&&!entry.name.startsWith('.'))walk(path.join(directory,entry.name));
        continue;
      }
      if(!entry.isFile())continue;
      const fullPath=path.join(directory,entry.name),relativePath=path.relative(sourceRoot,fullPath).split(path.sep).join('/'),suffix=path.extname(entry.name).toLowerCase();
      if(entry.name==='package.xml'){
        try{const match=fs.readFileSync(fullPath,'utf8').slice(0,131072).match(/<name>\s*([^<]+?)\s*<\/name>/);const name=match?.[1]?.trim()||path.basename(directory);if(name&&!packages.includes(name))packages.push(name);}catch{}
      }
      if(!allowedExt.has(suffix)&&entry.name!=='CMakeLists.txt'&&entry.name!=='package.xml'&&!entry.name.endsWith('.launch.py'))continue;
      let size=0,text='';try{size=fs.statSync(fullPath).size;if(size>524288)continue;if(fileCount>=750||totalBytes+size>6291456){truncated=true;return;}text=fs.readFileSync(fullPath,'utf8');}catch{continue;}
      fileCount++;totalBytes+=size;
      if(suffix==='.py')languages.add('Python');
      if(['.cpp','.cc','.cxx','.c','.h','.hh','.hpp'].includes(suffix))languages.add('C/C++');
      if(['.urdf','.xacro'].includes(suffix))hits.urdf.add(relativePath);
      if(entry.name.endsWith('.launch.py')||suffix==='.launch')hits.launch.add(relativePath);
      for(const [capability,patterns] of Object.entries(CAPABILITY_PATTERNS))if(patterns.some(pattern=>new RegExp(pattern,'im').test(text)))hits[capability].add(relativePath);
    }
  };
  walk(sourceRoot);
  let tuneVerified=false;
  try{const tune=JSON.parse(fs.readFileSync(path.join(root,'.roside','controller_tune.json'),'utf8')),sides=[tune.leftPid,tune.rightPid],protocolOk=tune.protocolVerified===true&&tune.drive==='diff2';tuneVerified=protocolOk&&(tune.pidControl===false||sides.every(side=>side&&['kp','ki','kd'].every(gain=>Number.isFinite(Number(side[gain]))&&Number(side[gain])>=0)));}catch{}
  let mappingVerified=false,mapName='';
  try{const result=JSON.parse(fs.readFileSync(path.join(root,'.roside','mapping_result.json'),'utf8'));mapName=String(result.mapName||'');const folder=/^[A-Za-z0-9_-]{1,40}$/.test(mapName)?path.join(root,'maps',mapName):'';mappingVerified=Boolean(folder&&fs.existsSync(path.join(folder,'map.yaml'))&&(fs.existsSync(path.join(folder,'map.pgm'))||fs.existsSync(path.join(folder,'map.png'))));}catch{}
  return {ok:true,workspace:root,sourceRoot,fileCount,packageCount:packages.length,packages:packages.sort().slice(0,30),languages:[...languages].sort(),truncated,
    capabilities:Object.keys(CAPABILITY_PATTERNS).map(id=>({id,detected:hits[id].size>0||(id==='mapping'&&mappingVerified),count:hits[id].size+(id==='mapping'&&mappingVerified?1:0),files:[...[...hits[id]].sort().slice(0,3),...(id==='mapping'&&mappingVerified?[`maps/${mapName}/map.yaml`]:[])].slice(0,4),...(id==='pid'?{tuneVerified}: {}),...(id==='mapping'?{mappingVerified,mapName}: {})}))};
}

const WIZARD_PROGRESS_RELATIVE = path.join('.roside', 'ros_wizard_progress.json');
const WIZARD_PROGRESS_VERSION = 2;

function emptySimulationWizardProgress() { return {version:WIZARD_PROGRESS_VERSION,completed:{}}; }

function readSimulationWizardProgress(workspace) {
  try {
    const value=JSON.parse(fs.readFileSync(path.join(path.resolve(String(workspace||'')),WIZARD_PROGRESS_RELATIVE),'utf8'));
    return value&&value.version===WIZARD_PROGRESS_VERSION&&value.completed&&typeof value.completed==='object'?value:emptySimulationWizardProgress();
  } catch { return emptySimulationWizardProgress(); }
}

function updateSimulationWizardProgress(workspace, update) {
  const root=path.resolve(String(workspace||'')),target=path.join(root,WIZARD_PROGRESS_RELATIVE),progress=readSimulationWizardProgress(root);
  update(progress.completed);
  progress.version=WIZARD_PROGRESS_VERSION;progress.updatedAt=new Date().toISOString();
  fs.mkdirSync(path.dirname(target),{recursive:true});
  const temporary=target+`.tmp-${process.pid}-${Date.now()}`;
  fs.writeFileSync(temporary,JSON.stringify(progress,null,2));fs.renameSync(temporary,target);
  return progress;
}

function resetSimulationWizardAfterFieldChange(workspace) {
  return updateSimulationWizardProgress(workspace,completed=>{
    completed.lidar={completedAt:new Date().toISOString(),evidence:'map.json'};
    delete completed.mapping;delete completed.navigation;
  });
}

function completeSimulationWizardMapping(workspace,mapName) {
  return updateSimulationWizardProgress(workspace,completed=>{
    completed.mapping={completedAt:new Date().toISOString(),mapName:String(mapName)};
    delete completed.navigation;
  });
}

function completeSimulationWizardNavigation(workspace,mapName) {
  return updateSimulationWizardProgress(workspace,completed=>{
    completed.navigation={completedAt:new Date().toISOString(),mapName:String(mapName),started:true};
  });
}

function inspectSimulationMissionArtifacts(workspace) {
  const root=path.resolve(String(workspace||'')),progress=readSimulationWizardProgress(root),mappingRecord=progress.completed.mapping,navigationRecord=progress.completed.navigation;
  const mapName=String(mappingRecord?.mapName||'');
  const mapFolder=/^[A-Za-z0-9_-]{1,40}$/.test(mapName)?path.join(root,'maps',mapName):'';
  let mapFolderExists=false;
  try { mapFolderExists=Boolean(mapFolder&&fs.statSync(mapFolder).isDirectory()); } catch {}
  const mappingDone=Boolean(mappingRecord?.completedAt&&mapFolderExists);
  const mapping={
    id:'mapping',detected:mappingDone,count:mappingDone?1:0,files:mappingDone?[`maps/${mapName}`,WIZARD_PROGRESS_RELATIVE]:[],resultCheck:true,wizardActionCheck:true,progressVersion:WIZARD_PROGRESS_VERSION,mapFolderExists,
    validationMessage:!mappingRecord
      ? 'ยังไม่ได้ทำภารกิจวาดแผนที่ — ต้องสำรวจและกด Save Map ใน Robot Playground'
      : !mapFolderExists
      ? `ยังไม่พบโฟลเดอร์ maps/${mapName} — กด Save Map ใน Robot Playground อีกครั้ง`
      : `กด Save Map ใน Robot Playground สำเร็จแล้ว · ${mappingRecord.mapName}`,
  };
  const sameMap=Boolean(mappingDone&&navigationRecord?.mapName===mappingRecord.mapName);
  const navigationDone=Boolean(sameMap&&navigationRecord?.started===true&&navigationRecord?.completedAt);
  const navigation={
    id:'navigation',detected:navigationDone,count:navigationDone?1:0,
    files:navigationDone?[WIZARD_PROGRESS_RELATIVE]:[],resultCheck:true,wizardActionCheck:true,progressVersion:WIZARD_PROGRESS_VERSION,mapFolderExists,
    validationMessage:!mappingDone
      ? 'ต้องทำและบันทึกภารกิจวาดแผนที่ให้สมบูรณ์ก่อน'
      : navigationDone
      ? `เปิดทดลองรัน Navigation บนแผนที่ “${mappingRecord.mapName}” สำเร็จแล้ว`
      : 'ยังไม่ผ่านภารกิจ — เข้าโหมด Navigation เลือก Saved Map แล้วกดเริ่ม Navigation',
  };
  return [mapping,navigation];
}

